// template for generating a LUT
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <ctype.h>
#include "../compose/compose.h"
#include "../compose/specs.h"


typedef struct {
  const char *name;
  const composed_spec_t *spec;
} spec_entry_t;

// Defining the multipliers that will be generated
static const spec_entry_t SPECS[] = {
  {"exact", &exact_spec},
  {"FPGA_ISH_1", &fpga_ish1},
  {"FPGA_ISH_2", &fpga_ish2},
  {"FPGA_ISH_3", &fpga_ish3},
  {"FPGA_ISH_4", &fpga_ish4},
  {"FPGA_ISH_5", &fpga_ish5},
};

static const composed_spec_t *lookup_spec(const char *name) {
  size_t n = sizeof(SPECS) / sizeof(SPECS[0]);
  for (size_t i = 0; i < n; i++) {
    if (strcmp(SPECS[i].name, name) == 0) return SPECS[i].spec;
  }
  return NULL;
}

// guard for TransAxx header as it differs slightly.
static int uppercase_into(const char *src, char *dst, size_t dst_size) {
  size_t len = strlen(src);
  if (len + 1 > dst_size) return -1;
  for (size_t i = 0; i < len; i++) dst[i] = (char)toupper((unsigned char)src[i]);
  dst[len] = '\0';
  return 0;
}

int main(int argc, char *argv[]) {
  if (argc < 2 || argc > 3) {
    fprintf(stderr, "usage: %s <multiplier_name> [adapt|transaxx]\n", argv[0]);
    fprintf(stderr, "example: %s FPGA_ISH_1 transaxx\n", argv[0]);
    fprintf(stderr, "target defaults to adapt if omitted\n");
    return 1;
  }

  const char *target = (argc == 3) ? argv[2] : "adapt";
  int is_transaxx;
  if (strcmp(target, "adapt") == 0) {
    is_transaxx = 0;
  } else if (strcmp(target, "transaxx") == 0) {
    is_transaxx = 1;
  } else {
    fprintf(stderr, "unknown target: %s (expected adapt or transaxx)\n", target);
    return 1;
  }

  const composed_spec_t *spec = lookup_spec(argv[1]);
  if (!spec) {
    fprintf(stderr, "unknown multiplier: %s\n", argv[1]);
    return 1;
  }

  /* Header */
  printf("/* Generated by generator.c. Do not edit by hand. */\n");
  printf("/* Multiplier: %s   Target: %s */\n\n", argv[1], target);
  if (is_transaxx) {
    char name_upper[64];
    if (uppercase_into(argv[1], name_upper, sizeof name_upper) < 0) {
      fprintf(stderr, "multiplier name too long for header guard\n");
      return 1;
    }
    printf("#ifndef _MUL8S_%s_H\n", name_upper);
    printf("#define _MUL8S_%s_H\n\n", name_upper);
    printf("const __device__ short lut[256][256] = {\n");
  } else {
    printf("#include <stdint.h>\n\n");
    printf("const int16_t lut[256][256] = {\n");
  }

  /* Body */
  for (int a_idx = 0; a_idx < 256; a_idx++){
    printf("\t{");
    for (int b_idx = 0; b_idx < 256; b_idx++){
      int16_t prod = mul_8bit_signed((int8_t)a_idx, (int8_t)b_idx, *spec);
      printf(" %d%s", prod, b_idx < 255 ? "," : "");
    }
    printf(" }%s\n", a_idx < 255 ? "," : "");
  }

  /* Footer */
  printf("};\n");
  if (is_transaxx) {
    printf("\n#endif\n");
  }
  return 0;
}
